/**
 * Dispatches weather code & isDay to appropriate broadsheet icon
 */
export function WeatherGlyph({ code = 0, isDay = 1, size = 24, className = '' }) {
  if ([95, 96, 99].includes(code)) {
    return <IconStorm size={size} className={className} />;
  }
  if ([56, 57, 66, 67, 71, 73, 75, 77, 85, 86].includes(code)) {
    return <IconSnow size={size} className={className} />;
  }
  if ([51, 53, 55, 61, 63, 65, 80, 81, 82].includes(code)) {
    return <IconRain size={size} className={className} />;
  }
  if ([45, 48].includes(code)) {
    return <IconFog size={size} className={className} />;
  }
  if ([2, 3].includes(code)) {
    return <IconCloud size={size} className={className} />;
  }
  return isDay ? <IconSun size={size} className={className} /> : <IconMoon size={size} className={className} />;
}
